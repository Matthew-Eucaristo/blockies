// Writes explorations/compiled.js: every default spec as real code, for hosts
// that forbid eval (such as a published artifact). Local runs do not need it.
// Usage: node explorations/build-compiled.mjs

import { writeFileSync } from 'node:fs';
import * as L from './lib/lattice.js';

const names = ['organism', 'messages', 'signals', 'rules', 'mind', 'sheet', 'kernel', 'nest'];
let out = '// Generated by build-compiled.mjs. Do not edit.\nexport default {\n';
for (const name of names) {
  const c = (await import(`./concepts/${name}.js`)).default;
  const helpers = Object.keys({ ...L, ...(c.helpers || {}) });
  const variants = c.variants ?? { default: c.spec };
  out += `  ${JSON.stringify(name)}: {\n`;
  for (const [v, src] of Object.entries(variants)) {
    out += `    ${JSON.stringify(v)}: (h) => {\n      const { ${helpers.join(', ')} } = h;\n      return (${src.trim()}\n      );\n    },\n`;
  }
  out += '  },\n';
}
out += '};\n';
writeFileSync(new URL('./compiled.js', import.meta.url), out);
console.log('wrote compiled.js', out.length, 'bytes');
